    // <folder>\staad-probe.s2k and staad-probe.std; notes gets FrameStd's notices
    public static string[] Write(string folder, string version, List<string> notes)
    {
        string s2k = Path.Combine(folder, "staad-probe.s2k"), std = Path.Combine(folder, "staad-probe.std");
        string text = Text(version);
        File.WriteAllBytes(s2k, Encoding.GetEncoding(28591).GetBytes(text));
        var m = FrameS2k.Read(S2kDoc.ParseText(text));
        FrameStd.Write(m, std, "staad-probe.s2k", notes);
        return new[] { s2k, std };
    }
