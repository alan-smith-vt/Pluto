    // fields that name a row within its table (beyond the first field), for matching probe rows to SAP's
    static readonly string[] RowKeys = { "DOF", "Point", "LoadPat", "LoadName", "CaseName", "GroupName", "ObjectLabel", "ObjectType", "Dir", "Type" };

    // Probe vs SAP's re-export: one line per table and field. Markdown, for the vault note.
    public static List<string> Check(string probePath, string exportPath)
    {
        var p = new Sap2kParser(probePath);
        var x = new Sap2kParser(exportPath);
        var o = new List<string>();
        o.Add("# Probe check: " + Path.GetFileName(probePath) + " against " + Path.GetFileName(exportPath));
        int same = 0, changed = 0, missing = 0;
        foreach (string t in p.TableNames())
        {
            var pr = p.GetTable(t);
            if (!x.HasTable(t)) { o.Add(""); o.Add("## " + t + "  -- NOT IN SAP'S EXPORT (" + pr.Count + " rows written)"); missing += pr.Count; continue; }
            var xr = x.GetTable(t);
            o.Add(""); o.Add("## " + t);
            var addedFields = new SortedSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var row in pr)
            {
                var hit = Match(row, xr);
                string id = Id(row);
                if (hit == null) { o.Add("- " + id + ": no matching row in SAP's export"); missing++; continue; }
                var notes = new List<string>();
                foreach (var kv in row)
                {
                    string v;
                    if (!hit.TryGetValue(kv.Key, out v)) { notes.Add(kv.Key + " MISSING"); missing++; }
                    else if (!Same(kv.Value, v)) { notes.Add(kv.Key + " " + kv.Value + " -> " + v); changed++; }
                    else same++;
                }
                foreach (var k in hit.Keys) if (!row.ContainsKey(k)) addedFields.Add(k);
                o.Add("- " + id + ": " + (notes.Count == 0 ? "all " + row.Count + " fields as written" : string.Join("; ", notes.ToArray())));
            }
            if (addedFields.Count > 0) o.Add("- fields SAP adds: " + string.Join(", ", addedFields.ToArray()));
            // the field order SAP writes (its first row), for new rows
            if (xr.Count > 0) o.Add("- SAP's field order: " + string.Join(" ", xr[0].Keys.ToArray()));
        }
        var extra = x.TableNames().Where(t => !p.HasTable(t)).ToList();
        o.Add("");
        o.Add("## Tables SAP wrote that the probe did not (" + extra.Count + ")");
        foreach (var t in extra)
        {
            var rows = x.GetTable(t);
            o.Add("- " + t + " (" + rows.Count + " rows)" + (rows.Count > 0 ? ": " + string.Join(" ", rows[0].Select(kv => kv.Key + "=" + kv.Value).ToArray()) : ""));
        }
        o.Insert(1, "");
        o.Insert(2, string.Format(Inv, "{0} fields as written, {1} changed, {2} missing", same, changed, missing));
        return o;
    }

    static string Id(Dictionary<string, string> row)
    {
        var parts = new List<string>();
        int k = 0;
        foreach (var kv in row) { if (k++ == 0 || RowKeys.Contains(kv.Key, StringComparer.OrdinalIgnoreCase)) parts.Add(kv.Key + "=" + kv.Value); }
        return string.Join(" ", parts.ToArray());
    }

    // the SAP row with the same first field (and row keys), else the one sharing the most fields
    static Dictionary<string, string> Match(Dictionary<string, string> row, List<Dictionary<string, string>> rows)
    {
        var first = row.First();
        Dictionary<string, string> best = null;
        int bestScore = -1;
        foreach (var r in rows)
        {
            string v;
            if (!r.TryGetValue(first.Key, out v) || !Same(v, first.Value)) continue;
            int score = 0;
            bool keysOk = true;
            foreach (var kv in row)
            {
                string w;
                if (!r.TryGetValue(kv.Key, out w)) continue;
                if (Same(w, kv.Value)) score++;
                else if (RowKeys.Contains(kv.Key, StringComparer.OrdinalIgnoreCase)) keysOk = false;
            }
            if (keysOk && score > bestScore) { best = r; bestScore = score; }
        }
        return best;
    }

    static bool Same(string a, string b)
    {
        if (string.Equals((a ?? "").Trim(), (b ?? "").Trim(), StringComparison.OrdinalIgnoreCase)) return true;
        double x, y;
        if (double.TryParse(a, NumberStyles.Float, Inv, out x) && double.TryParse(b, NumberStyles.Float, Inv, out y))
            return Math.Abs(x - y) <= 1e-6 * Math.Max(1, Math.Max(Math.Abs(x), Math.Abs(y)));
        return false;
    }
